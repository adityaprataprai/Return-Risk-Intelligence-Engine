def main():
    parser = argparse.ArgumentParser(description="Phase 1 Data Validation")
    parser.add_argument("--config", type=str, default="config/simulation/world_a.yaml",
                        help="Simulation config file path")
    args = parser.parse_args()

    config_path = Path(args.config)
    if not config_path.exists():
        print(f"[ERROR] Config file not found: {config_path}")
        sys.exit(1)
    config = load_config(config_path)
    print(f"Validating Phase 1 data for world_id={config.get('world_id')} seed={config.get('random_seed')}")

    failures = []

    if not validate_file_existence(failures):
        sys.exit(1)

    validate_schemas(failures)
    validate_primary_keys(failures)
