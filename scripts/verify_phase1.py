def load_parquet(path):
    """Load a Parquet file and return Polars DataFrame if exists."""
    if not path.exists():
        print(f"[ERROR] File not found: {path}")
        return None
    return pl.read_parquet(path)


def check(condition, pass_msg, fail_msg, failures):
    """Record a check result."""
    if condition:
        print(f"[PASS] {pass_msg}")
        return True
    else:
        print(f"[FAIL] {fail_msg}")
        failures.append(fail_msg)
        return False


def any_none(*dfs):
    """Return True if any dataframe is None."""
    return any(df is None for df in dfs)


def extract_transaction_id(events_df):
    """
    Extract transaction_id from the events DataFrame.
    The events schema may store transaction_id either as a direct column
    or inside the entity_ids field (struct, JSON string, or python dict string).
    """
    if "transaction_id" in events_df.columns:
        return events_df

    if "order_id" in events_df.columns:
        return events_df.with_columns(pl.col("order_id").alias("transaction_id"))

    # Try struct field extraction
    try:
        if isinstance(events_df.schema.get("entity_ids"), pl.Struct):
            fields = [f.name for f in events_df.schema["entity_ids"].fields]
            if "transaction_id" in fields:
                return events_df.with_columns(
                    pl.col("entity_ids").struct.field("transaction_id").alias("transaction_id")
                )
            elif "order_id" in fields:
                return events_df.with_columns(
                    pl.col("entity_ids").struct.field("order_id").alias("transaction_id")
                )
    except Exception:
        pass

    # Try regex extraction for string entity_ids (handles both JSON and python dict strings)
    try:
        extracted = events_df.with_columns(
            pl.col("entity_ids")
            .str.extract(r"""['"](?:transaction_id|order_id)['"]\s*:\s*['"]?([a-zA-Z0-9_-]+)""", 1)
            .alias("transaction_id")
        )
        if extracted.filter(pl.col("transaction_id").is_not_null()).shape[0] > 0:
            return extracted
    except Exception:
        pass

    # Try JSON string extraction
    try:
        extracted = events_df.with_columns(
            pl.coalesce(
                pl.col("entity_ids").str.json_extract(dtype=pl.String, query_path="$.transaction_id"),
                pl.col("entity_ids").str.json_extract(dtype=pl.String, query_path="$.order_id"),
            ).alias("transaction_id")
        )
        if extracted.filter(pl.col("transaction_id").is_not_null()).shape[0] > 0:
            return extracted
    except Exception:
        pass

    # If all fail, return original (may cause join errors later, but validation will catch)
    print("[WARN] Could not extract transaction_id from events; delivery-before-return check may fail.")
    return events_df


def load_config(config_path):
    """Load simulation config YAML."""
